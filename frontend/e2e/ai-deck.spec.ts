import { expect, test } from "./fixtures";

/**
 * AI whole-deck authoring (W3-F) in mock mode. The e2e backend has no AI key
 * (`LLM_*`/`GEMINI_API_KEY` blank), so every step runs on labelled placeholders:
 * the run checks the whole flow (form, outline review, slides with speaker notes,
 * the deck opening in the builder) and that nothing passes mock data off as AI.
 */

const MOCK_NOTICE = "Generated with mock data (no AI key configured)";

test("mock mode: plan an outline, review it, generate a deck with notes and open it in the builder", async ({ host }) => {
  const name = `E2E AI deck ${Date.now()}`;
  const page = await host.open(`/presentation/create?name=${encodeURIComponent(name)}&mode=ai`);

  // A new deck opens the AI dialog on "Whole deck" and says up front that there is no AI key.
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("heading", { name: "Generate a whole deck" })).toBeVisible();
  await expect(dialog.getByRole("tab", { name: "Whole deck" })).toHaveAttribute("aria-selected", "true");
  await expect(dialog.getByTestId("ai-deck-mock-capability")).toBeVisible();

  // Step 1: the request. The topic is seeded from the deck name.
  const topic = dialog.getByLabel("Topic");
  await expect(topic).toHaveValue(name);
  await topic.fill("Zero trust security");
  await dialog.getByLabel("Audience (optional)").fill("new engineers");
  await dialog.getByRole("radio", { name: "Casual" }).click();
  await dialog.getByLabel("Slides", { exact: true }).fill("8");
  await dialog.getByRole("button", { name: "Plan outline" }).click();

  // Step 2: the outline to review; it is labelled as mock data and nothing is stored yet.
  await expect(dialog.getByRole("heading", { name: "Review the outline" })).toBeVisible();
  await expect(dialog.getByTestId("ai-deck-mock-notice")).toContainText(MOCK_NOTICE);
  await expect(dialog.getByTestId("ai-deck-outline-count")).toHaveText("8 slides");
  await expect(dialog.getByLabel("Deck title", { exact: true })).toHaveValue(name);

  // The author edits it: reword a slide, drop one, add one.
  await dialog.getByLabel("What slide 2 covers").fill("Explain why perimeters fail");
  await dialog.getByRole("button", { name: "Remove slide 3" }).click();
  await expect(dialog.getByTestId("ai-deck-outline-count")).toHaveText("7 slides");
  await dialog.getByRole("button", { name: "Add a slide to section 1" }).click();
  await expect(dialog.getByTestId("ai-deck-outline-count")).toHaveText("8 slides");
  // A new slide has no intent yet: the outline cannot be sent until it says what the slide covers.
  await dialog.getByRole("button", { name: "Write slides and speaker notes" }).click();
  const problem = dialog.getByRole("alert");
  await expect(problem).toContainText("Say what slide");
  const empty = /slide (\d+) covers/.exec(await problem.innerText())![1];
  await dialog.getByLabel(`What slide ${empty} covers`).fill("Recap the three ideas to remember");
  await dialog.getByRole("button", { name: "Write slides and speaker notes" }).click();

  // Step 3: the deck exists, with notes, and says where it came from.
  const result = dialog.getByTestId("ai-deck-result");
  await expect(result).toBeVisible({ timeout: 60_000 });
  await expect(result.getByTestId("ai-deck-mock-notice")).toContainText(MOCK_NOTICE);
  await expect(result.getByText("Generated by AI")).toHaveCount(0);
  await expect(result.getByTestId("ai-deck-summary")).toHaveText("8 slides, 8 with speaker notes");
  await expect(result.getByTestId("ai-deck-slides").getByRole("listitem")).toHaveCount(8);
  await expect(result.getByText("Notes: Placeholder notes (mock mode").first()).toBeVisible();

  // Open it in the builder: the deck is the one being edited, and the mock label stays on the page.
  await result.getByRole("button", { name: "Open in builder" }).click();
  await expect.poll(() => new URL(page.url()).searchParams.get("aiSource")).toBe("mock");
  await expect.poll(() => new URL(page.url()).searchParams.get("id")).toMatch(/^[a-f0-9]{24}$/);
  await expect(dialog).toHaveCount(0);
  const deckId = new URL(page.url()).searchParams.get("id")!;
  await expect(page.getByRole("status").filter({ hasText: MOCK_NOTICE })).toBeVisible();
  await expect(page.getByLabel("Deck title", { exact: true })).toHaveValue(name);
  await expect(page.getByRole("list", { name: "Slides" }).getByRole("button", { name: /^Slide \d+ of 8:/ })).toHaveCount(8);

  // What the API stores: a draft deck in the host's workspace, notes on every slide, nothing graded wrongly.
  const stored = await host.getDeck(deckId);
  expect(stored.title).toBe(name);
  expect(stored).toMatchObject({ status: "draft" });
  expect(stored.slides).toHaveLength(8);
  for (const slide of stored.slides) {
    expect(String(slide.notes)).toMatch(/mock mode/i);
  }
  expect(stored.slides.map((slide) => slide.type)).toContain("select_answer");
  expect(JSON.stringify(stored.slides)).toContain("Explain why perimeters fail");

  // The builder keeps the notes when the author saves (it does not strip fields it does not edit).
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByText("Presentation deck updated!")).toBeVisible();
  const saved = await host.getDeck(deckId);
  expect(saved.slides.every((slide) => String(slide.notes).length > 0)).toBe(true);

  // The notice can be dismissed.
  await page.getByRole("button", { name: "Dismiss this notice" }).click();
  await expect(page.getByTestId("ai-deck-mock-notice")).toHaveCount(0);
});

test("the dialog offers quick slides too, and the form validates before planning", async ({ host }) => {
  const page = await host.open("/presentation/create?name=E2E%20quick&mode=ai");
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("heading", { name: "Generate a whole deck" })).toBeVisible();

  // Validation: a short topic and no categories are refused before any request.
  await dialog.getByLabel("Topic").fill("ab");
  await dialog.getByRole("button", { name: "Plan outline" }).click();
  await expect(dialog.getByText("Enter a topic of at least 3 characters.")).toBeVisible();
  await expect(dialog.getByRole("heading", { name: "Review the outline" })).toHaveCount(0);

  await dialog.getByLabel("Topic").fill("Team retrospective");
  for (const category of ["Content slides", "Polls", "Quiz questions"]) {
    await dialog.getByRole("switch", { name: new RegExp(category) }).click();
  }
  await dialog.getByRole("button", { name: "Plan outline" }).click();
  await expect(dialog.getByText("Include at least one kind of slide.")).toBeVisible();

  // The old quick-slides generator is still there.
  await dialog.getByRole("tab", { name: "Quick slides" }).click();
  await expect(dialog.getByRole("heading", { name: "Generate deck with AI" })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "Generate slides" })).toBeVisible();
});
